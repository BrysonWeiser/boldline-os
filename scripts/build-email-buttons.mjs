// Draws every fixed email button as a picture (see netlify/lib/email-button.mjs for why) into
// marketing-site/email/<version>/, and writes their sizes to netlify/lib/email-button-images.mjs.
// Run after adding or renaming a button in a client email:
//   NODE_PATH=<dir with playwright> node scripts/build-email-buttons.mjs
// Changing how the buttons LOOK? Bump VERSION, so inboxes that cached the old pictures fetch the new ones.
import { createRequire } from "node:module";
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { scanEmailButtonLabels } from "./email-button-labels.mjs";

const VERSION = "v1";
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "marketing-site", "email", VERSION);
const { chromium } = createRequire(import.meta.url)("playwright");
const exe = (() => { const r = "/opt/pw-browsers"; const d = existsSync(r) && readdirSync(r).find((x) => /^chromium-\d+$/.test(x)); return d ? join(r, d, "chrome-linux/chrome") : undefined; })();

export const slugOf = (label) => label.toLowerCase().replace(/&/g, " and ").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

// The same button the email draws in code: gold, 10px corners, 14px bold Inter in near black, 13px x 32px padding.
const page = `<!doctype html><html><head><style>
@font-face{font-family:Inter;font-weight:100 900;src:url("file://${join(ROOT, "marketing-site/fonts/inter-latin.woff2")}") format("woff2")}
html,body{margin:0;background:transparent}
#b{display:inline-block;padding:13px 32px;border-radius:10px;background:#C8A84B;color:#15110A;font:700 14px/18px Inter,sans-serif;white-space:nowrap;-webkit-font-smoothing:antialiased}
</style></head><body><span id="b"></span></body></html>`;

const labels = scanEmailButtonLabels(ROOT);
mkdirSync(OUT, { recursive: true });
const b = await chromium.launch({ executablePath: exe, args: ["--no-sandbox", "--allow-file-access-from-files"] });
const pg = await b.newPage({ viewport: { width: 800, height: 200 }, deviceScaleFactor: 2 });
const tmp = join(OUT, "_render.html");
writeFileSync(tmp, page);
await pg.goto("file://" + tmp);
const images = {};
for (const label of labels) {
  await pg.evaluate((t) => { document.getElementById("b").textContent = t + " →"; }, label);
  await pg.evaluate(() => document.fonts.ready);
  const el = await pg.$("#b");
  const box = await el.boundingBox();
  const file = slugOf(label) + ".png";
  await el.screenshot({ path: join(OUT, file), omitBackground: true });
  images[label] = { file, w: Math.round(box.width), h: Math.round(box.height) };
  console.log(`${file}  ${images[label].w}x${images[label].h}`);
}
await b.close();
(await import("node:fs")).unlinkSync(tmp);

writeFileSync(join(ROOT, "netlify/lib/email-button-images.mjs"),
  `// Generated by scripts/build-email-buttons.mjs. Do not edit by hand: run it again after adding a button.\n` +
  `export const EMAIL_BUTTON_VERSION = ${JSON.stringify(VERSION)};\n` +
  `export const EMAIL_BUTTON_IMAGES = ${JSON.stringify(images, null, 2)};\n`);
console.log(`${labels.length} buttons -> marketing-site/email/${VERSION}/`);
