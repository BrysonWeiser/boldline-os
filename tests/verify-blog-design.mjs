// The blog's look (redesign, 2026-10-07). Bryson: the blog "seems outdated and not worth anyones time".
// What has to stay true:
//  1. Blog pages use the SAME stylesheet, footer, phone bar and scripts as every other page (generated, never copied).
//  2. Every post has a cover picture, drawn in code, that fits its topic and carries no emoji or dash.
//  3. The words a visitor reads follow the standing rules: no "local businesses", no em dashes, no invented claims.
//  4. A website article offers the website booking; everything else offers the free check and the ads call.
//  5. A broken article never shows empty headings, even before the self-repair rewrites it.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const MK = join(ROOT, "marketing-site");
let pass = 0; const fails = [];
const ok = (what, cond, detail = "") => { if (cond) pass++; else fails.push(`${what}${detail ? " — " + detail : ""}`); };
const read = (f) => readFileSync(join(MK, f), "utf8");

const render = read("netlify/lib/blog-render.mjs"), index = read("netlify/functions/blog-index.mjs"), post = read("netlify/functions/blog-post.mjs");
const chrome = await import("../marketing-site/netlify/lib/site-chrome.mjs");
const { outputs } = await import("../scripts/build-marketing-site.mjs");

// 1. Same pieces as the rest of the site
ok("the shared pieces are generated by the site builder", outputs["netlify/lib/site-chrome.mjs"] === read("netlify/lib/site-chrome.mjs"));
ok("🔴 blog pages load the site's stylesheet, not the old blog one", /\$\{HEAD_ASSETS\}/.test(render) && chrome.HEAD_ASSETS.includes('href="/site.css"') && !/href="\/blog\.css"/.test(render));
ok("the site stylesheet carries the blog styles", read("site.css").includes(".bx-card{") && read("site.css").includes(".art-body{"));
ok("the footer, phone bar and scripts are the site's own", /\$\{FOOTER\}\$\{STICKY\}\$\{SCRIPTS\}/.test(render) && chrome.FOOTER.includes('class="x-foot"') && chrome.SCRIPTS.includes("/site.js"));
ok("no second header script fighting site.js", !/document\.querySelector\('header'\)/.test(render));
ok("the test-copy guard still opens every blog page", render.indexOf('<script src="/test-copy.js"></script>') > 0 && render.indexOf('<script src="/test-copy.js"></script>') < render.indexOf("${HEAD_ASSETS}"));

// 2. Covers
const { coverSVG, coverKind } = await import("../marketing-site/netlify/lib/blog-cover.mjs");
const samples = [["Google Ads", "Why Negative Keywords Save More Money"], ["Meta Ads", "Facebook ads for detailers"], ["Websites", "What a $1,500 website gets you"],
  ["Lead Follow-Up", "How fast to call a new lead"], ["Budgeting", "How much to spend on ads"], ["Strategy", "Should you pause ads on weekends"], ["Trades", "More booked jobs for handymen"], ["Getting Started", "Are you ready for ads"]];
const kinds = new Set(samples.map(([c, t]) => coverKind(c, t)));
ok("eight topics draw at least seven different pictures", kinds.size >= 7, [...kinds].join(","));
for (const [c, t] of samples) {
  const svg = coverSVG({ slug: t, category: c, title: t });
  ok(`${c}: a cover is drawn`, svg.startsWith("<svg") && svg.includes('viewBox="0 0 640 360"'));
  ok(`${c}: no emoji or dash in the picture`, !/\p{Extended_Pictographic}/u.test(svg) && !/[—–]/.test(svg));
}
ok("a title can't break out of the picture", !coverSVG({ slug: "x", category: "<b>", title: "</svg><script>alert(1)</script>" }).includes("<script>"));
ok("two posts on the same topic don't look identical", coverSVG({ slug: "a", category: "Budgeting", title: "Budget" }) !== coverSVG({ slug: "b", category: "Budgeting", title: "Budget" }));

// 3. Words
const visible = (s) => s.split("\n").filter((l) => !/^\s*\/\//.test(l)).join("\n");
for (const [n, s] of [["blog-render", render], ["blog-index", index], ["blog-post", post]]) {
  ok(`🔴 ${n}: never says "local businesses"`, !/local (service )?business/i.test(visible(s)));
  ok(`🔴 ${n}: no em or en dashes in what visitors read`, !/[—–]|&mdash;|&ndash;/.test(visible(s)));
}

// 4. Offers by topic
const { offerHTML, CAL, CAL_WEB } = await import("../marketing-site/netlify/lib/blog-render.mjs");
ok("🔴 a website article books a website call", offerHTML("Websites", "x").includes(CAL_WEB) && !offerHTML("Websites", "x").includes(CAL + '"'));
ok("an ads article offers the free check and the ads call", offerHTML("Google Ads", "x").includes('href="/free-check/"') && offerHTML("Google Ads", "x").includes(CAL));

// 5. Broken articles
ok("🔴 empty headings are dropped when the article is drawn", /replace\(\/<h2\[\^>\]\*>\\s\*<\\\/h2>\/g, ""\)/.test(post));
ok("dates are Phoenix dates", (index.match(/timeZone: "America\/Phoenix"/g) || []).length >= 1 && (post.match(/timeZone: "America\/Phoenix"/g) || []).length >= 2);

if (fails.length) console.log(fails.map((f) => "  FAIL  " + f).join("\n"));
console.log(`verify-blog-design: ${pass} passed, ${fails.length} failed`);
process.exit(fails.length ? 1 : 0);
